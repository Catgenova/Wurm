/**
 * Every migration, in order, in one file.
 *
 * The SQL editor in the dashboard is one box, and asking somebody to paste ten
 * files into it in the right order is asking them to get it wrong once. This
 * is those ten files, concatenated, so setting a project up by hand is a
 * single copy and a single Run.
 *
 * Generated. Change a migration, run `npm run db:bundle`, commit both.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'supabase/migrations';
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const out = [
  '-- Wurm Iso: the whole island, in one go.',
  '--',
  '-- Generated by scripts/bundle-sql.mjs from supabase/migrations/. Do not edit:',
  '-- run `npm run db:bundle` instead.',
  '--',
  '-- Paste the lot into the SQL editor in the Supabase dashboard and press Run.',
  '-- Safe to run more than once: everything here is create-or-replace or',
  '-- create-if-not-exists.',
  '',
  ...files.flatMap((f) => [
    '',
    `-- ${'='.repeat(70)}`,
    `-- ${f}`,
    `-- ${'='.repeat(70)}`,
    '',
    readFileSync(join(dir, f), 'utf8').trimEnd(),
  ]),
  '',
].join('\n');
writeFileSync('supabase/all.sql', out);
console.log(`supabase/all.sql: ${files.length} migrations, ${out.split('\n').length} lines`);
