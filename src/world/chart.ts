let cells: Uint8Array | null = null;

/** The whole table, unpacked the first time it is asked for. */
export function chartCells(): Uint8Array {
  if (cells) return cells;
  const out = new Uint8Array(CHART_CELLS * CHART_CELLS);
  ROWS.forEach((row, y) => {
    let x = 0;
    for (const run of row.split('.')) {
      const n = parseInt(run.slice(1), 36);
      out.fill(Number(run[0]), y * CHART_CELLS + x, y * CHART_CELLS + x + n);
      x += n;
    }
  });
  cells = out;
  return out;
}

/** The index in `REGIONS` of the island a point of a world `size` across is on: the island's `region_at`. */
export function chartRegion(x: number, y: number, size: number): number {
  const at = (v: number): number => Math.min(CHART_CELLS - 1, Math.max(0, Math.floor((v * CHART_CELLS) / size)));
  return chartCells()[at(y) * CHART_CELLS + at(x)];
}
